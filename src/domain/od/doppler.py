"""Доплер первого порядка и связь оси водопада с принятой частотой."""

from __future__ import annotations

import numpy as np

from .constants import C_KM_S


def fac(v_km_s: np.ndarray | float) -> np.ndarray | float:
    """Доплеровский множитель `1 − v/c`. Удаляется (`v > 0`) — частота ниже."""
    return 1.0 - np.asarray(v_km_s, dtype=float) / C_KM_S


def received_freq_hz(
    center_freq_hz: float, f_offset_hz: np.ndarray | float
) -> np.ndarray:
    """Принятая на площадке частота из смещения на водопаде, Гц.

        f_abs = f_центра − f_смещение(t)

    Здесь раньше стояла формула `f_центра + f_смещение − f_центра·v/c`
    из допущения, что клиент ведёт приёмник по предсказанию и на оси
    отложен **остаток** доплера. **Замер это опроверг, и дважды.**

    Первый замер (фаза 0, наблюдение 1527888): смещение проходит полную
    S-кривую размахом 16314 Гц при размахе сырого доплера 16343 Гц, то есть
    отношение 1.00 — коррекции при записи не было, — и притом с обратным
    знаком. Второй замер (фаза 1, `scripts/phase1/sweep.py` по корпусу):
    из четырёх мыслимых вариантов выигрывает «сырой, ось инвертирована»
    на **всех** извлечённых наблюдениях восьми разных станций, с запасом
    по RMS от 2 до 225 раз. Значит это свойство сети, а не станции,
    и хранить его в снимке наблюдения не нужно (открытый вопрос 9 закрыт).

    Знак остаётся **измеряемым**, а не постулированным: `end_to_end.py`
    и `sweep.py` продолжают перебирать все четыре варианта и печатать запас
    до следующего. Запас порядка единицы означает, что варианты неразличимы,
    то есть трек ненадёжен, — и это диагностика для человека, а не повод
    молча взять формулу отсюда.
    """
    return center_freq_hz - np.asarray(f_offset_hz, dtype=float)
